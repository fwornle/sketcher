/**
 * Lays out text as strokes. `size` is the cap height in pixels; letters advance by
 * 5 grid units (4 wide plus a gap). Returns the strokes and their tight box.
 */
export function layoutText(text, x, y, size) {
  const s = size / 6;
  const strokes = [];
  [...text.toUpperCase()].forEach((ch, i) => {
    const glyph = GLYPHS[ch];
    if (!glyph) throw new Error(`No glyph for '${ch}'`);
    for (const stroke of glyph) strokes.push(stroke.map(([gx, gy]) => [x + (i * 5 + gx) * s, y + gy * s]));
  });
  return { strokes, bbox: [x, y, x + (text.length * 5 - 1) * s, y + size] };
}

/** Width in pixels of `text` at cap height `size`. */
export function textWidth(text, size) {
  return ((text.length * 5 - 1) * size) / 6;
}
